create or replace function public.naxvo_respond_quote(p_request_id bigint,p_action text,p_reason text default '')
returns jsonb language plpgsql security definer set search_path=public as $$
declare me bigint:=public.naxvo_current_profile_id(); r public.solicitudes%rowtype; accepted boolean;
begin
  select * into r from public.solicitudes where id=p_request_id for update;
  if r.cliente_id<>me or r.cotizacion_estado<>'pendiente' then raise exception 'La cotización ya no está pendiente'; end if;
  if p_action='aceptar' then
    update public.solicitudes set cotizacion_estado='aceptada',precio_aceptado=true,cotizacion_respondida_at=now(),fecha_acordada=cotizacion_fecha_propuesta,hora_acordada=cotizacion_hora_propuesta where id=r.id;
    accepted:=true;
    perform public.naxvo_add_event(r.id,me,'cotizacion_aceptada','Cotización aceptada','El cliente aceptó la cotización.');
  elsif p_action='rechazar' then
    if length(trim(p_reason))<5 then raise exception 'Indica qué debe cambiar en la propuesta'; end if;
    update public.solicitudes set cotizacion_estado='rechazada',precio_aceptado=false,cotizacion_respondida_at=now(),cotizacion_rechazo_motivo=trim(p_reason) where id=r.id;
    accepted:=false;
    perform public.naxvo_add_event(r.id,me,'cotizacion_rechazada','Cambios solicitados',trim(p_reason));
  else raise exception 'Acción inválida'; end if;
  perform public.naxvo_notify(r.trabajador_id,me,r.id,'cotizacion_respuesta',case when accepted then 'Cotización aceptada' else 'Solicitaron cambios' end,case when accepted then 'El cliente aceptó tu propuesta.' else trim(p_reason) end);
  return jsonb_build_object('request_id',r.id,'accepted',accepted);
end $$;

