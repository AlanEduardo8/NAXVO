-- Usuarios: propio, administrador o contraparte de una solicitud ya relacionada.
drop policy if exists usuarios_select on public.usuarios;
create policy usuarios_select on public.usuarios for select to authenticated using (
  auth_user_id = auth.uid()
  or public.naxvo_is_admin()
  or exists (
    select 1 from public.solicitudes s
    where (s.cliente_id = public.naxvo_current_profile_id() or s.trabajador_id = public.naxvo_current_profile_id())
      and (s.cliente_id = usuarios.id or s.trabajador_id = usuarios.id)
  )
);
drop policy if exists usuarios_update_own on public.usuarios;
create policy usuarios_update_own on public.usuarios for update to authenticated
using (id = public.naxvo_current_profile_id() or public.naxvo_is_admin())
with check (id = public.naxvo_current_profile_id() or public.naxvo_is_admin());

