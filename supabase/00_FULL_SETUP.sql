create or replace function public.naxvo_current_profile_id()
returns bigint
language sql
stable
security definer
set search_path = public
as $$
  select id from public.usuarios where auth_user_id = auth.uid() limit 1
$$;

create or replace function public.naxvo_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists(
    select 1 from public.usuarios
    where auth_user_id = auth.uid() and tipo = 'admin' and estado_cuenta = 'activo'
  )
$$;

create or replace function public.naxvo_touch_updated_at()
returns trigger language plpgsql as $$
begin new.fecha_actualizacion = now(); return new; end $$;

create or replace function public.naxvo_handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  m jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  role text := case when m->>'tipo' = 'trabajador' then 'trabajador' else 'cliente' end;
  years integer := case when coalesce(m->>'anos_experiencia','') ~ '^\d+$' then (m->>'anos_experiencia')::integer else 0 end;
begin
  insert into public.usuarios(
    auth_user_id,nombre,apellidos,email,tipo,telefono,profesion,especialidad,especialidades,
    anos_experiencia,ciudad,estado,zona_servicio,biografia,experiencia,verificacion_estado,disponible
  ) values (
    new.id,
    coalesce(nullif(trim(m->>'nombre'),''), split_part(new.email,'@',1)),
    coalesce(m->>'apellidos',''),
    lower(new.email),
    role,
    nullif(m->>'telefono',''),
    nullif(m->>'profesion',''),
    nullif(m->>'especialidad',''),
    nullif(m->>'especialidades',''),
    least(years,80),
    nullif(m->>'ciudad',''),
    nullif(m->>'estado',''),
    nullif(m->>'zona_servicio',''),
    nullif(m->>'biografia',''),
    nullif(m->>'experiencia',''),
    case when role='trabajador' then 'pendiente' else 'no_aplica' end,
    case when role='trabajador' then false else true end
  )
  on conflict (auth_user_id) do nothing;
  return new;
end $$;

drop trigger if exists on_auth_user_created_naxvo on auth.users;
create trigger on_auth_user_created_naxvo
after insert on auth.users
for each row execute function public.naxvo_handle_new_auth_user();

create or replace function public.naxvo_guard_user_update()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if coalesce(current_setting('naxvo.internal', true),'') <> '1' and not public.naxvo_is_admin() then
    new.auth_user_id := old.auth_user_id;
    new.email := old.email;
    new.tipo := old.tipo;
    new.modo_dual_habilitado := old.modo_dual_habilitado;
    new.estado_cuenta := old.estado_cuenta;
    new.motivo_suspension := old.motivo_suspension;
    new.suspendido_hasta := old.suspendido_hasta;
    new.verificado := old.verificado;
    new.verificacion_estado := old.verificacion_estado;
    new.verificacion_nota := old.verificacion_nota;
    new.calificacion_promedio := old.calificacion_promedio;
    new.destacado := old.destacado;
    if new.disponible and not old.verificado and old.tipo='trabajador' then
      new.disponible := false;
    end if;
  end if;
  new.fecha_actualizacion := now();
  return new;
end $$;

drop trigger if exists trg_guard_usuario on public.usuarios;
create trigger trg_guard_usuario before update on public.usuarios
for each row execute function public.naxvo_guard_user_update();

create or replace function public.naxvo_guard_prof_verification()
returns trigger language plpgsql set search_path=public as $$
begin
  new.fecha_actualizacion := now();
  if coalesce(current_setting('naxvo.internal',true),'') <> '1' and not public.naxvo_is_admin() then
    new.usuario_id := public.naxvo_current_profile_id();
    new.estado := 'pendiente';
    new.nota_revision := null;
    new.revisado_por := null;
    new.fecha_revision := null;
  end if;
  return new;
end $$;
drop trigger if exists trg_guard_prof_verification on public.verificaciones_profesionales;
create trigger trg_guard_prof_verification before insert or update on public.verificaciones_profesionales
for each row execute function public.naxvo_guard_prof_verification();

create or replace function public.naxvo_guard_client_verification()
returns trigger language plpgsql set search_path=public as $$
begin
  new.fecha_actualizacion := now();
  if coalesce(current_setting('naxvo.internal',true),'') <> '1' and not public.naxvo_is_admin() then
    new.usuario_id := public.naxvo_current_profile_id();
    new.estado := case when new.ine_path is not null and new.rostro_path is not null then 'pendiente' else 'borrador' end;
    new.nota_revision := null;
    new.revisado_por := null;
    new.fecha_revision := null;
  end if;
  return new;
end $$;
drop trigger if exists trg_guard_client_verification on public.verificaciones_clientes;
create trigger trg_guard_client_verification before insert or update on public.verificaciones_clientes
for each row execute function public.naxvo_guard_client_verification();

