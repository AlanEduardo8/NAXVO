  order by (s.trabajador_id=me.id) desc,s.fecha_creacion desc
$$;

create or replace function public.naxvo_accept_request(p_request_id bigint)
returns jsonb language plpgsql security definer set search_path=public as $$
declare me bigint:=public.naxvo_current_profile_id(); r public.solicitudes%rowtype;
begin
  select * into r from public.solicitudes where id=p_request_id for update;
  if r.id is null then raise exception 'Solicitud no encontrada'; end if;
  if not exists(select 1 from public.usuarios where id=me and tipo='trabajador' and verificado and estado_cuenta='activo') then raise exception 'Debes verificar tu perfil profesional'; end if;
  if r.estado<>'pendiente' then raise exception 'La solicitud ya no está disponible'; end if;
  if r.trabajador_id is not null and r.trabajador_id<>me then raise exception 'Esta solicitud está reservada para otro profesional'; end if;
  update public.solicitudes set trabajador_id=me,estado='asignado',fecha_asignacion=now() where id=r.id;
  perform public.naxvo_add_event(r.id,me,'solicitud_aceptada','Profesional asignado','El profesional aceptó la solicitud y puede preparar una cotización.');
  perform public.naxvo_notify(r.cliente_id,me,r.id,'solicitud_aceptada','Solicitud aceptada','El profesional aceptó tu solicitud.');
  return jsonb_build_object('request_id',r.id,'accepted',true);
end $$;

create or replace function public.naxvo_decline_request(p_request_id bigint)
returns jsonb language plpgsql security definer set search_path=public as $$
declare me bigint:=public.naxvo_current_profile_id(); r public.solicitudes%rowtype;
begin
  if not exists(select 1 from public.usuarios where id=me and tipo='trabajador' and verificado and estado_cuenta='activo') then raise exception 'Debes tener un perfil profesional verificado'; end if;
  select * into r from public.solicitudes where id=p_request_id for update;
  if r.id is null or r.estado<>'pendiente' then raise exception 'La solicitud ya no está disponible'; end if;
  if r.trabajador_id is not null and r.trabajador_id<>me then raise exception 'Esta solicitud está reservada para otro profesional'; end if;
  insert into public.solicitud_declines(solicitud_id,trabajador_id) values(r.id,me) on conflict do nothing;
  if r.trabajador_id=me then
    update public.solicitudes set trabajador_id=null where id=r.id;
    perform public.naxvo_notify(r.cliente_id,me,r.id,'solicitud_rechazada','Solicitud no aceptada','El profesional no pudo tomar la solicitud; ahora queda disponible para otros profesionales.');
  end if;
  return jsonb_build_object('request_id',r.id,'declined',true);
end $$;

create or replace function public.naxvo_submit_quote(p_request_id bigint,p_amount numeric,p_detail text,p_date date,p_time time)
returns jsonb language plpgsql security definer set search_path=public as $$
declare me bigint:=public.naxvo_current_profile_id(); r public.solicitudes%rowtype;
begin
  if p_amount<=0 then raise exception 'Monto inválido'; end if;
  select * into r from public.solicitudes where id=p_request_id for update;
  if r.trabajador_id<>me or r.estado<>'asignado' then raise exception 'No puedes cotizar esta solicitud'; end if;
