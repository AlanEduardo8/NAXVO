create or replace function public.naxvo_create_request(p_payload jsonb)
returns jsonb language plpgsql security definer set search_path=public as $$
declare me bigint := public.naxvo_current_profile_id(); rid bigint; worker bigint; serviceid bigint; addr text;
begin
  if me is null then raise exception 'Sesión inválida'; end if;
  if not exists(select 1 from public.usuarios where id=me and tipo='cliente' and estado_cuenta='activo') then raise exception 'Activa el modo cliente para crear solicitudes'; end if;
  worker := nullif(p_payload->>'trabajador_id','')::bigint;
  serviceid := nullif(p_payload->>'servicio_publicado_id','')::bigint;
  addr := concat_ws(', ',nullif(p_payload->>'calle',''),nullif(p_payload->>'numero',''),nullif(p_payload->>'colonia',''),nullif(p_payload->>'ciudad',''),nullif(p_payload->>'estado_dir',''),nullif(p_payload->>'codigo_postal',''));
  if coalesce(length(trim(p_payload->>'descripcion')),0)<15 then raise exception 'La descripción debe tener al menos 15 caracteres'; end if;
  if worker is not null and not exists(select 1 from public.usuarios where id=worker and tipo='trabajador' and verificado and estado_cuenta='activo') then raise exception 'El profesional seleccionado no está disponible'; end if;
  insert into public.solicitudes(cliente_id,trabajador_id,servicio_publicado_id,servicio,descripcion,direccion,latitud,longitud,estado_dir,fecha_preferida,hora_preferida,metodo_pago,urgencia,instrucciones,calle,numero,colonia,ciudad,codigo_postal)
  values(me,worker,serviceid,coalesce(nullif(p_payload->>'servicio',''),'Servicio'),p_payload->>'descripcion',addr,
    nullif(p_payload->>'latitud','')::numeric,nullif(p_payload->>'longitud','')::numeric,nullif(p_payload->>'estado_dir',''),
    nullif(p_payload->>'fecha_preferida','')::date,nullif(p_payload->>'hora_preferida','')::time,
    case when p_payload->>'metodo_pago'='mercadopago' then 'mercadopago' else 'efectivo' end,
    coalesce(nullif(p_payload->>'urgencia',''),'media'),nullif(p_payload->>'instrucciones',''),nullif(p_payload->>'calle',''),nullif(p_payload->>'numero',''),nullif(p_payload->>'colonia',''),nullif(p_payload->>'ciudad',''),nullif(p_payload->>'codigo_postal',''))
  returning id into rid;
  perform public.naxvo_add_event(rid,me,'solicitud_creada','Solicitud creada','El cliente registró una nueva solicitud.');
  if worker is not null then perform public.naxvo_notify(worker,me,rid,'solicitud_directa','Nueva solicitud directa','Un cliente te envió una solicitud.'); end if;
  return jsonb_build_object('request_id',rid);
end $$;

create or replace function public.naxvo_get_opportunities()
returns table(
 id bigint, servicio text, descripcion text, estado text, finalizacion_estado text, urgencia text, fecha_creacion timestamptz,
 fecha_preferida date, hora_preferida time, presupuesto numeric, ciudad text, estado_dir text, direccion text, calle text, numero text,
 colonia text, codigo_postal text, instrucciones text, metodo_pago text, directa boolean, cliente_nombre text
)
language sql stable security definer set search_path=public as $$
  select s.id,s.servicio,s.descripcion,s.estado,s.finalizacion_estado,s.urgencia,s.fecha_creacion,s.fecha_preferida,s.hora_preferida,s.presupuesto,
         s.ciudad,s.estado_dir,s.direccion,s.calle,s.numero,s.colonia,s.codigo_postal,s.instrucciones,s.metodo_pago,(s.trabajador_id=public.naxvo_current_profile_id()) as directa,
         trim(concat(c.nombre,' ',c.apellidos)) as cliente_nombre
  from public.solicitudes s join public.usuarios c on c.id=s.cliente_id
  join public.usuarios me on me.id=public.naxvo_current_profile_id()
